// Package claudemd renders findings into a managed section of CLAUDE.md
// (or .cursorrules etc.) so the next AI prompt sees the current architecture
// state. Only the region between the markers is rewritten; everything the
// user wrote by hand is preserved.
package claudemd

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/nonchan7720/depgraph/pkg/domain/rules"
	"github.com/nonchan7720/depgraph/pkg/domain/view"
)

const (
	startMarker = "<!-- depgraph:start -->"
	endMarker   = "<!-- depgraph:end -->"
)

// Render builds the markdown body for the managed section.
func Render(stats view.Stats, findings []rules.Finding) string {
	var b strings.Builder
	fmt.Fprintf(&b, "## Dependency graph (auto-generated by depgraph, %s)\n\n", time.Now().Format("2006-01-02 15:04"))
	fmt.Fprintf(&b, "%d packages, %d files, %d symbols, %d package-level import edges.\n\n",
		stats.Packages, stats.Files, stats.Symbols, stats.Imports)

	if len(findings) == 0 {
		b.WriteString("No architectural violations detected. Keep it that way: do not introduce import cycles, respect layer boundaries, and reuse existing functions instead of re-implementing them.\n")
		return b.String()
	}

	b.WriteString("### Rules for the AI assistant\n\n")
	b.WriteString("- Before adding an import, check it does not create a cycle or cross a forbidden layer listed below.\n")
	b.WriteString("- Before writing a new function/class, search for existing code that already does it (same name, or the same logic under another name) and reuse or consolidate it.\n")
	b.WriteString("- Prefer fixing the violations below over adding new code that depends on them.\n\n")

	byRule := map[string][]rules.Finding{}
	order := []string{"import-cycle", rules.RuleModuleCycle, "layer-violation", "duplicate-code", "god-package", "duplicate-symbol",
		rules.RuleUnusedExport, rules.RuleUnreachableFile, rules.RuleUnreachablePackage, rules.RuleExternalUnclassified}
	known := map[string]bool{}
	for _, r := range order {
		known[r] = true
	}
	var extra []string
	for _, f := range findings {
		if !known[f.Rule] && byRule[f.Rule] == nil {
			extra = append(extra, f.Rule)
		}
		byRule[f.Rule] = append(byRule[f.Rule], f)
	}
	// rules without a fixed title (configured or new ones) follow, by name
	sort.Strings(extra)
	order = append(order, extra...)
	titles := map[string]string{
		"import-cycle":                 "Import cycles (must fix)",
		rules.RuleModuleCycle:          "Import cycles between modules / workspace packages (must fix)",
		"layer-violation":              "Layer violations (must fix)",
		"duplicate-code":               "Duplicated code (extract the shared logic and reuse it; do not add another copy)",
		"god-package":                  "God packages (high fan-in; avoid adding more dependents)",
		"duplicate-symbol":             "Duplicate symbols (consolidate before adding more)",
		rules.RuleUnusedExport:         "Unused exports (nothing in the project uses them: delete them, do not build on them)",
		rules.RuleUnreachableFile:      "Unreachable files (no entry point imports them: delete or wire them up)",
		rules.RuleUnreachablePackage:   "Unreachable Go packages (no main package or test imports them)",
		rules.RuleExternalUnclassified: "External imports ext: layers could not classify (not checked for frameworks; do not take this as a pass)",
	}
	for _, rule := range order {
		fs := byRule[rule]
		if len(fs) == 0 {
			continue
		}
		title := titles[rule]
		if title == "" {
			title = rule
		}
		fmt.Fprintf(&b, "### %s\n\n", title)
		for i, f := range fs {
			if n := listLimit[rule]; n > 0 && i == n {
				fmt.Fprintf(&b, "- ... and %d more (`depgraph check` lists them all)\n", len(fs)-n)
				break
			}
			fmt.Fprintf(&b, "- %s\n", f.Message)
		}
		b.WriteString("\n")
	}
	return b.String()
}

// listLimit caps the rules that can list one item per declaration or file:
// the section is read with every prompt.
var listLimit = map[string]int{
	rules.RuleUnusedExport: 20, rules.RuleUnreachableFile: 20, rules.RuleUnreachablePackage: 20,
}

// Update writes body into the managed section of path, creating the file if needed.
func Update(path, body string) error {
	section := startMarker + "\n" + body + endMarker + "\n"

	existing, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	content := string(existing)

	start := strings.Index(content, startMarker)
	end := strings.Index(content, endMarker)
	var out string
	switch {
	case start >= 0 && end > start:
		out = content[:start] + section + strings.TrimPrefix(content[end+len(endMarker):], "\n")
	case content == "":
		out = section
	default:
		if !strings.HasSuffix(content, "\n") {
			content += "\n"
		}
		out = content + "\n" + section
	}
	return os.WriteFile(path, []byte(out), 0o644)
}

// Writer writes evaluations into the managed section of the file at Path
// (implements analysis.ReportWriter).
type Writer struct {
	Path string
}

// Write renders stats and findings and replaces the managed section.
func (w Writer) Write(stats view.Stats, findings []rules.Finding) error {
	if err := Update(w.Path, Render(stats, findings)); err != nil {
		return fmt.Errorf("update %s: %w", w.Path, err)
	}
	return nil
}
