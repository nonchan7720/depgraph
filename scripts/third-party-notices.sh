#!/usr/bin/env bash
# Generates THIRD_PARTY_NOTICES.md from the dependencies that end up in the
# depgraph binary: Go modules linked into the depgraph binary (module root) and the runtime npm
# dependencies of web/ (bundled into the embedded UI). Run from the repo root.
#   scripts/third-party-notices.sh            write THIRD_PARTY_NOTICES.md
#   scripts/third-party-notices.sh --check    fail if the file is out of date
set -euo pipefail

out=THIRD_PARTY_NOTICES.md
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

license_file() {
  local f
  for f in "$1"/LICENSE "$1"/LICENSE.txt "$1"/LICENSE.md "$1"/COPYING; do
    [ -f "$f" ] && { echo "$f"; return 0; }
  done
  return 1
}

# gotreesitter embeds tree-sitter grammar tables from upstream grammar
# repositories. List the ones linked into the binary (the per-language
# grammars/<name> packages depgraph imports) with their license, from the
# module's own audit (licenses/grammars.json + licenses/texts/<SPDX>.txt).
gotreesitter_grammars() {
  local dir=$1 names
  names=$(go list -deps -f '{{.ImportPath}}' . \
            | sed -n 's#^github.com/odvcencio/gotreesitter/grammars/\([^/]*\)$#\1#p' \
            | grep -v -x -e grammar_blobs -e runtime | sort -u)
  [ -n "$names" ] || return 0
  echo "#### Embedded tree-sitter grammars"
  echo
  echo "gotreesitter embeds grammar tables generated from the following upstream"
  echo "tree-sitter grammar repositories (license audit: licenses/grammars.json in the module)."
  echo
  node - "$dir" $names <<'EOF'
const fs = require("fs"), path = require("path");
const [dir, ...names] = process.argv.slice(2);
const audit = JSON.parse(fs.readFileSync(path.join(dir, "licenses/grammars.json"), "utf8"));
for (const name of names) {
  const e = audit.entries.find((x) => x.name === name);
  if (!e) { console.error(`no license audit entry for grammar ${name}`); process.exit(1); }
  const text = path.join(dir, "licenses/texts", `${e.spdx}.txt`);
  if (!fs.existsSync(text)) { console.error(`no license text for ${e.spdx} (grammar ${name})`); process.exit(1); }
  console.log(`##### ${name} (${e.spdx})\n`);
  console.log(`${e.repo} at ${e.ref}\n`);
  console.log("```");
  for (const c of e.copyright_holders || []) console.log(c);
  if ((e.copyright_holders || []).length) console.log();
  process.stdout.write(fs.readFileSync(text, "utf8").replace(/\n*$/, "\n"));
  console.log("```\n");
}
EOF
}

{
  echo "# Third-party notices"
  echo
  echo "depgraph is licensed under the Apache License 2.0 (see LICENSE)."
  echo "The binary includes the following third-party software."
  echo "This file is generated by \`scripts/third-party-notices.sh\`; do not edit by hand."
  echo

  echo "## Go modules"
  echo
  while read -r path version dir; do
    f=$(license_file "$dir") || { echo "no license file for $path@$version" >&2; exit 1; }
    echo "### $path $version"
    echo
    echo '```'
    cat "$f"
    echo '```'
    echo
    if [ "$path" = "github.com/odvcencio/gotreesitter" ]; then
      gotreesitter_grammars "$dir"
    fi
  done < <(go list -deps -f '{{if .Module}}{{.Module.Path}} {{.Module.Version}} {{.Module.Dir}}{{end}}' . \
             | grep -v '^github.com/nonchan7720/depgraph ' | sort -u)

  echo "## npm packages (embedded browser UI)"
  echo
  for name in $(node -e 'console.log(Object.keys(require("./web/package.json").dependencies || {}).sort().join(" "))'); do
    dir="web/node_modules/$name"
    version=$(node -e "console.log(require('./$dir/package.json').version)")
    license=$(node -e "console.log(require('./$dir/package.json').license || '')")
    f=$(license_file "$dir") || { echo "no license file for $name@$version" >&2; exit 1; }
    echo "### $name $version ($license)"
    echo
    if [ "$name" = "elkjs" ]; then
      echo "Used under the Eclipse Public License 2.0. Source code: https://github.com/kieler/elkjs"
      echo
    fi
    echo '```'
    cat "$f"
    echo '```'
    echo
  done
} > "$tmp"

if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "$tmp" "$out"; then
    echo "$out is out of date; run: mise run licenses" >&2
    exit 1
  fi
  echo "$out is up to date"
else
  mv "$tmp" "$out"
  trap - EXIT
  echo "wrote $out"
fi
